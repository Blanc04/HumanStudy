# 리스트는 함수 안에서 직접 변경될 수 있는 mutable 자료형이다.
ref(b)
# 함수 안에서 원본 리스트에 4가 추가되었으므로
# 함수 반환값을 다시 저장하지 않아도 b의 내용이 바뀌어 있다.
print(b) # [1, 2, 3, 4]가 나오는 이유는 위의 ref(a)에서 4를 추가했기 때문임.

