# 두 값을 전달받아 덧셈 결과와 뺄셈 결과를 모두 반환하는 함수이다.
def add_sub(a, b):
    # 두 값을 더한 결과를 x에 저장한다.
    x = a + b
    # a에서 b를 뺀 결과를 y에 저장한다.
    y = a - b
    # 두 값을 쉼표로 구분하여 반환하면 튜플 형태로 반환된다.
    return x, y

# 반환된 두 값이 하나의 튜플로 c에 저장된다.
c = add_sub(1, 2)
# c의 자료형과 값을 출력한다.
print(type(c), c)
# 반환된 튜플의 첫 번째 값은 d, 두 번째 값은 e에 각각 저장된다.
# 이를 튜플 언패킹이라고 한다.
d, e = add_sub(1, 2)
# 반환된 두 값이 하나의 튜플로 x에 저장된다.
x = add_sub(1, 2)

