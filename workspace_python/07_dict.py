# 딕셔너리 선언 방법 1
# 중괄호 {}를 사용하면 비어 있는 딕셔너리가 만들어진다.
a = {}

# 딕셔너리 선언 방법 2
# dict() 함수를 사용해도 비어 있는 딕셔너리가 만들어진다.
a = dict()

# a의 자료형을 출력한다.
# 결과: <class 'dict'>
print(type(a))

# 여러 개의 key와 value를 가진 딕셔너리 선언
b = {
    # '이름'은 key, '호랑이심장'은 value
    '이름': '호랑이심장',
    # '직업'이라는 key에 '마법사'라는 value 저장
    '직업': '마법사',
    # 딕셔너리 안에 또 다른 딕셔너리를 넣을 수도 있다.
    # 이것을 중첩 딕셔너리라고 한다.
    '스킬': {
        '공격': '고백',
        '방어': '철벽남',
        'javascript': '상',
    }
}
# 딕셔너리 b 전체를 출력한다.
print(b)

# dict() 함수로 딕셔너리 만들기
# 이 방식에서는 a와 b가 문자열 key가 된다.
# 결과: {'a': 10, 'b': 20}
c = dict(a=10, b=20)
print(c)

# 자바스크립트 객체처럼 b.이름으로 접근할 수는 없다.
# 파이썬 딕셔너리는 대괄호 안에 key를 적어서 값에 접근한다.
# b.이름

# '이름'이라는 key의 value를 출력한다.
# 결과: 호랑이심장
print(b['이름'])

# 존재하지 않는 key를 대괄호 방식으로 찾으면 KeyError가 발생한다.
# print(b['이름2'])

# get()을 사용해서 '이름' key의 값을 가져온다.
# 결과: 호랑이심장
print(b.get('이름'))
# get()으로 존재하지 않는 key를 찾으면 에러 대신 None이 나온다.
print(b.get('이름2'))  # 결과: None
# get(key, 기본값)
# key가 없으면 두 번째로 작성한 기본값을 반환한다.
print(b.get('이름2', '이름없음'))  # 결과: 이름없음

# 중첩 딕셔너리의 값에 접근하는 방법
# 먼저 '스킬' 딕셔너리를 찾고,
# 그 안에서 '공격' key의 값을 찾는다.
# 결과: 고백
print(b['스킬']['공격'])

# get()을 연속으로 사용해서 중첩 딕셔너리의 값에 접근한다.
# b.get('스킬')의 결과는 스킬 딕셔너리이고,
# 그 딕셔너리에서 get('공격')을 실행한다.
# 결과: 고백
print(b.get('스킬').get('공격'))


# '스킬2'라는 key가 없으면 빈 딕셔너리 {}를 대신 사용한다.
# 빈 딕셔너리에서 '공격'을 찾는데,
# '공격'도 없으므로 기본값 0을 반환한다.
#
# 그냥 b.get('스킬2').get('공격')이라고 쓰면
# b.get('스킬2')의 결과가 None이므로 에러가 발생한다.
print(b.get('스킬2', {}).get('공격', 0))

# 딕셔너리에 새로운 key와 value를 추가한다.
# '직업2'라는 key가 없으므로 새로 만들어진다.
b['직업2'] = '도적2'
# 추가된 딕셔너리를 출력한다.
print(b)


# '스킬'이라는 key가 b 안에 있는지 확인한다.
# 있으면 True, 없으면 False
print('스킬' in b)
# b의 '스킬' 딕셔너리 안에 '공격' key가 있는지 확인한다.
print('공격' in b['스킬'])
# b의 '스킬' 딕셔너리 안에 '공격' key가 없는지 확인한다.
# 실제로 '공격'이 있으므로 결과는 False
print('공격' not in b['스킬'])


# 딕셔너리 b에 들어 있는 최상위 key의 개수를 구한다.
# 중첩 딕셔너리 안의 key는 따로 세지 않는다.
print(len(b))


# keys()
# 딕셔너리에 들어 있는 모든 key를 가져온다.
e = b.keys()
print(e)


# values()
# 딕셔너리에 들어 있는 모든 value를 가져온다.
f = b.values()
print(f)

# values()의 결과는 바로 인덱스로 접근할 수 없다.
# 먼저 list로 변환한 뒤 첫 번째 값을 가져온다.
print(list(f)[0])


# items()
# 딕셔너리의 key와 value를 한 쌍으로 가져온다.
# 각 항목은 (key, value) 형태의 튜플로 나온다.
g = b.items()
print(g)


# 문자열 선언
a = 'hello'

# 문자열을 list로 변환한다.
# 각 문자가 순서대로 리스트에 들어간다.
# 결과: ['h', 'e', 'l', 'l', 'o']
print(list(a))

# 문자열을 set으로 변환한다.
# 중복된 문자인 'l'은 하나만 남는다.
# 결과의 출력 순서는 달라질 수 있다.
print(set(a))


# set
# 중복된 값을 제거해서 관리하는 자료형
# 값의 순서는 보장하지 않는다.


# 딕셔너리 b를 다시 선언한다.
# 이전 b의 내용은 사라지고 새로운 딕셔너리로 덮어쓴다.
b = {
    '이름': '호랑이심장',
    '직업': '마법사',
    '스킬': {
        '공격': '고백',
        '방어': '철벽남',
        'javascript': '상',
    }
}

# update()
# 기존 딕셔너리의 값을 여러 개 수정할 수 있다.
# '이름'과 '직업' key가 이미 있으므로 기존 값이 변경된다.
b.update(이름='타이거', 직업='강사')
print(b)

# update()에 존재하지 않는 key를 넣으면 새 key가 추가된다.
# '이름', '직업'은 수정되고 '나이'는 새로 추가된다.
b.update(이름='타이거', 직업='강사', 나이=20)
print(b)

# pop(key)
# 지정한 key와 해당 value를 딕셔너리에서 삭제한다.
# 삭제한 value를 반환한다.
#
# '나이' key가 없으면 KeyError가 발생한다.
# c = b.pop('나이')

# pop(key, 기본값)
# '나이' key가 있으면 삭제하고 그 값을 반환한다.
# '나이' key가 없으면 에러 대신 두 번째 값인 0을 반환한다.
c = b.pop('나이', 0)
# '나이'가 삭제된 딕셔너리를 출력한다.
print(b)
# 삭제된 '나이'의 값 또는 기본값 0을 출력한다.
print(c)

# 딕셔너리의 pop()은 삭제할 key를 반드시 전달해야 한다.
# 리스트의 pop()처럼 아무 값 없이 사용할 수 없다.
# c = b.pop()

# popitem()
# 딕셔너리의 마지막 key-value 쌍을 삭제하고 반환한다.
# 반환 결과는 (key, value) 형태의 튜플이다.
c = b.popitem()
# 삭제된 key-value 쌍을 출력한다.
print(c)
# 마지막 항목이 삭제된 딕셔너리를 출력한다.
print(b)

# 문자열이 들어 있는 리스트 선언
a = ['a', 'b', 'c']

# 리스트 a의 값과 동일한 key를 직접 작성한 딕셔너리
b = {
    'a': 0,
    'b': 0,
    'c': 0
}

# b를 빈 딕셔너리로 다시 선언한다.
# 바로 위에서 만든 b의 내용은 사라진다.
b = {}

# 리스트 a의 첫 번째 값인 'a'를 key로 사용한다.
# 결과: {'a': 0}
b[a[0]] = 0

# 리스트 a의 두 번째 값인 'b'를 key로 사용한다.
# 결과: {'a': 0, 'b': 0}
b[a[1]] = 0

# dict.fromkeys(리스트)
# 리스트의 각 값을 딕셔너리의 key로 만든다.
# value를 따로 지정하지 않으면 모두 None이 들어간다.
#
# 결과:
# {'a': None, 'b': None, 'c': None}
c = dict.fromkeys(a)
print(c)

# 딕셔너리를 반복문에 직접 넣으면 key만 순서대로 나온다.
for i in c:
    # 현재 key를 출력한다.
    print(i)

    # 현재 key에 저장된 value를 출력한다.
    # c의 모든 value는 현재 None이다.
    print(c[i])

# items()를 사용하면 key와 value를 동시에 꺼낼 수 있다.
for k, v in c.items():
    # k에는 key가 들어가고,
    # v에는 해당 key의 value가 들어간다.
    print(k, v)